player_x = 400
player_y = 300
player_speed = 5

while True:
	for event in pygame.event.get():
		if event.type == pygame.QUIT:
			pygame.quit()
			sys.exit()
	keys = pygame.key.get_pressed()
	if keys[pygame.K_LEFT] or keys[pygame.K_a]:
		player_x -= player_speed
	if keys[pygame.K_RIGHT] or keys[pygame.K_d]:
		player_x += player_speed
	if keys[pygame.K_UP] or keys[pygame.K_w]:
		player_y -= player_speed
	if keys[pygame.K_DOWN] or keys[pygame.K_s]:
		player_y += player_speed

	tile_rects = []

	for row_index, row in enumerate(game_map):
		for col_index, tile in enumerate(row):
			if tile == 1:
				block_x = col_index * TILE_SIZE
				block_y = row_index * TILE_SIZE


				tile_rects.append(pygame.Rect(block_x, block_y, TILE_SIZE, TILE_SIZE))
	
	screen.fill((135, 206, 235))

	for tile in tile_rects:
		pygame.draw.rect(screen, (34, 139, 34), tile)
	
	pygame.draw.rect(screen, (255,0,0), (player_x, player_y, 32, 32))

	pygame.display.flip()
	clock.tick(60)